#!/usr/bin/env node
'use strict';

const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');

const EXPECTED_BLOB_SHA='44954a1248493d8cc336f121ce5cce394cee9ac0';
const SOURCE_REPOSITORY='PokeAPI/pokeapi';
const SOURCE_PATH='data/v2/csv/pokemon_species_names.csv';
const SOURCE_RETRIEVED_AT='2026-08-06';
const LANGUAGE_BY_ID=Object.freeze({1:'ja',6:'de',7:'es',9:'en'});

function gitBlobSha(content){
  return crypto.createHash('sha1').update(`blob ${content.length}\0`).update(content).digest('hex');
}

function parseCsvLine(line){
  const fields=[];let value='',quoted=false;
  for(let index=0;index<line.length;index+=1){
    const character=line[index];
    if(character==='"'){
      if(quoted&&line[index+1]==='"'){value+='"';index+=1;}
      else quoted=!quoted;
    }else if(character===','&&!quoted){fields.push(value);value='';}
    else value+=character;
  }
  fields.push(value);return fields;
}

function generate(source){
  const actualSha=gitBlobSha(source);
  if(actualSha!==EXPECTED_BLOB_SHA)throw new Error(`Source blob mismatch: expected ${EXPECTED_BLOB_SHA}, received ${actualSha}`);
  const catalogs={en:{},ja:{},es:{},de:{}};
  for(const line of source.toString('utf8').split(/\r?\n/).slice(1)){
    if(!line)continue;
    const[speciesId,languageId,name]=parseCsvLine(line),locale=LANGUAGE_BY_ID[Number(languageId)],id=Number(speciesId);
    if(!locale)continue;
    if(!Number.isInteger(id)||id<=0||!String(name||'').trim())throw new Error(`Invalid ${locale} mapping for species ${speciesId}`);
    if(Object.prototype.hasOwnProperty.call(catalogs[locale],id))throw new Error(`Duplicate ${locale} mapping for species ${id}`);
    catalogs[locale][id]=name;
  }
  const counts=Object.fromEntries(Object.entries(catalogs).map(([locale,names])=>[locale,Object.keys(names).length]));
  if(Object.values(counts).some(count=>count!==1025))throw new Error(`Incomplete source coverage: ${JSON.stringify(counts)}`);
  const literal=value=>JSON.stringify(Object.fromEntries(Object.entries(value).sort((a,b)=>Number(a[0])-Number(b[0]))));
  return `(function(global){\n  // Generated by scripts/generate-pokemon-name-catalog.cjs from the pinned\n  // PokéAPI species-name CSV. Do not edit individual names by hand.\n  const SOURCE=Object.freeze({\n    repository:'${SOURCE_REPOSITORY}',\n    path:'${SOURCE_PATH}',\n    gitBlobSha:'${EXPECTED_BLOB_SHA}',\n    retrievedAt:'${SOURCE_RETRIEVED_AT}',\n    sourceSpecies:1025,\n    languageIds:Object.freeze({ja:1,de:6,es:7,en:9})\n  });\n  const en=Object.freeze(${literal(catalogs.en)});\n  const ja=Object.freeze(${literal(catalogs.ja)});\n  const es=Object.freeze(${literal(catalogs.es)});\n  const de=Object.freeze(${literal(catalogs.de)});\n  global.PogoPokemonNameCatalogs=Object.freeze({en,ja,es,de});\n  global.PogoPokemonNameCatalogSource=SOURCE;\n})(window);\n`;
}

const sourcePath=process.argv[2],outputPath=process.argv[3]||path.join(__dirname,'..','js','i18n','pokemonNames','catalog.js');
if(!sourcePath){console.error('Usage: node scripts/generate-pokemon-name-catalog.cjs <pokemon_species_names.csv> [output]');process.exit(2);}
const generated=generate(fs.readFileSync(path.resolve(sourcePath))).replace('{en,ja,es,de}','{en,ja,es,de,}');
fs.writeFileSync(path.resolve(outputPath),generated,'utf8');
console.log(JSON.stringify({status:'generated',sourceBlobSha:EXPECTED_BLOB_SHA,speciesPerLocale:1025,output:path.relative(process.cwd(),path.resolve(outputPath))}));
